import type { AgentBackend } from './api';
export type CrewEvent = { type: string; requestId?: string; title?: string; detail?: unknown; options?: { id: string; label: string }[]; questions?: { id: string; question: string }[] };
export type CrewAuditEvent = { at: number; kind: string; text: string; detail?: unknown };
export type CrewTranscript = { sessionKey: string; backend: AgentBackend; cwd: string; sessionPath?: string; label: string; prompt: string; report: string; events: CrewEvent[] };
export type CrewTask = { id: string; kind: string; backend: AgentBackend; model?: { provider: string; id: string } | null; outcome: string; scope: string[]; dependencies: string[]; checks: string[]; covers?: string[]; status: string; attempts: number; history: CrewTranscript[]; report?: string; approvedPlan?: string; error?: string; worktree?: { path: string }; gate?: CrewGate; commit?: string; integrationBefore?: string; lastFailure?: { error?: string; gate?: CrewGate; review?: string } };
export type CrewGate = { ok: boolean; results: { command: string; ok: boolean; output: string }[] };
export type CrewCriterion = { id: string; text: string; source?: 'lead' | 'user' };
export type CrewQuestion = { id: string; question: string; options?: string[]; answer?: string };
export type CrewStepModel = { backend: AgentBackend; model?: { provider: string; id: string } | null; effort?: string };
export type CrewDecisions = { investigate: 'none' | 'plan' | 'diagnose'; investigateWhy: string; prosecute: boolean; prosecuteWhy: string; review: boolean; reviewWhy: string; checks: string[] };
export type CrewFinding = { id: string; criterion?: string | null; severity: string; file?: string; line?: number | null; text: string; selected?: boolean };
export type CrewReview = { pass: number; fromCommit?: string; toCommit?: string; verdict?: string; verdicts?: Record<string, string>; findings?: CrewFinding[]; sent?: { ids?: string[]; note?: string } };
export type CrewRun = {
  autonomous?: boolean;
  rationale?: string;
  routingHistory?: CrewTranscript[];
  id: string;
  owner: string;
  phase?: string;
  repairs?: number;
  request: string;
  mode: string;
  status: string;
  tasks: CrewTask[];
  integration?: { path: string };
  error?: string;
  finalReview?: string;
  diff?: string;
  gate?: CrewGate;
  finalHistory?: CrewTranscript[];
  createdAt?: number;
  updatedAt?: number;
  cwd?: string;
  reviewer?: { backend: AgentBackend; model?: { provider: string; id: string } | null };
  summary?: string;
  criteria?: CrewCriterion[];
  questions?: CrewQuestion[];
  assumptions?: string[];
  checkMenu?: string[];
  decisions?: CrewDecisions;
  leadDecisions?: CrewDecisions;
  lead?: { backend?: string; rounds?: number; history?: CrewTranscript[] };
  models?: { builder?: CrewStepModel; investigator?: CrewStepModel; prosecutor?: CrewStepModel; reviewer?: CrewStepModel };
  investigation?: { approach?: string; contract?: string; concerns?: string[]; history?: CrewTranscript[]; workers?: { id: string; outcome: string; scope: string[]; dependsOn?: string[]; covers?: string[] }[] };
  prosecution?: { status?: string; round?: number; findings?: unknown[]; owned?: string[]; log?: { round?: number; by?: string; report?: string; findings?: unknown[] }[]; lastReport?: string; cap?: boolean };
  reviews?: CrewReview[];
  events?: CrewAuditEvent[];
  integrator?: { sessionKey?: string; backend?: AgentBackend; history?: CrewTranscript[]; turns?: number; restarts?: number };
  reviewTranscripts?: CrewTranscript[];
  result?: string;
};
